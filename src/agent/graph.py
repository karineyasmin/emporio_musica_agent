"""LangGraph compilation and execution workflow for the customer support agent."""

from typing import Literal

from langchain_core.messages import SystemMessage
from langgraph.checkpoint.memory import MemorySaver
from langgraph.graph import END, START, StateGraph
from langgraph.prebuilt import ToolNode

from src.agent.llm import get_fallback_llm, get_llm
from src.agent.prompts import SYSTEM_PROMPT
from src.agent.state import AgentState
from src.agent.tools import ALL_TOOLS
from src.config.config import settings
from src.utils.logger import logger


def call_model(state: AgentState) -> dict:
    """Executes the LLM with system instructions and current conversation context.

    Args:
        state: Current conversational state holding the messages list.

    Returns:
        dict: New message output generated by the language model.
    """
    logger.info("Executing model node...")
    llm = get_llm(ALL_TOOLS)
    messages = list(state["messages"])

    # Ensure system prompt is explicitly set at the head of the context
    if not messages or not isinstance(messages[0], SystemMessage):
        messages = [SystemMessage(content=SYSTEM_PROMPT)] + messages

    try:
        response = llm.invoke(messages)
    except Exception as primary_error:
        if not settings.GOOGLE_API_KEY:
            raise

        logger.warning(
            "Primary LLM failed during inference; retrying with Ollama fallback: "
            f"{primary_error}"
        )
        try:
            response = get_fallback_llm(ALL_TOOLS).invoke(messages)
        except Exception as fallback_error:
            logger.error(
                f"Both primary and fallback LLMs failed: {fallback_error}",
                exc_info=True,
            )
            raise RuntimeError(
                "The primary and fallback language models are unavailable."
            ) from fallback_error
    return {"messages": [response]}


def should_continue(state: AgentState) -> Literal["tools", "__end__"]:
    """Determines whether the graph transitions to tool execution or terminates turn.

    Args:
        state: Current conversational state.

    Returns:
        Literal["tools", "__end__"]: Destination node identifier.
    """
    last_message = state["messages"][-1]
    if hasattr(last_message, "tool_calls") and last_message.tool_calls:
        logger.info(
            f"Routing to tools: {[call['name'] for call in last_message.tool_calls]}"
        )
        return "tools"
    return END


def create_agent_graph():
    """Builds and compiles the customer service ReAct state graph.

    Returns:
        CompiledStateGraph: Compiled workflow with in-memory persistence.
    """
    workflow = StateGraph(AgentState)

    workflow.add_node("agent", call_model)
    workflow.add_node("tools", ToolNode(ALL_TOOLS))

    workflow.add_edge(START, "agent")
    workflow.add_conditional_edges("agent", should_continue, ["tools", END])
    workflow.add_edge("tools", "agent")

    checkpointer = MemorySaver()
    return workflow.compile(checkpointer=checkpointer)


agent_executor = create_agent_graph()
