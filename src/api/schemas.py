"""Pydantic schemas for API request and response data transfer objects."""

from pydantic import BaseModel, Field


class ChatRequest(BaseModel):
    """Payload contract for user chat messages."""

    message: str = Field(
        ...,
        min_length=1,
        description="User text message sent to the store agent.",
        examples=["Quais opções de violão até R$ 1000?"],
    )
    session_id: str = Field(
        default="default-session",
        description="Unique customer conversation identifier for session state persistence.",
        examples=["user-session-123"],
    )


class ChatResponse(BaseModel):
    """Payload contract for agent replies."""

    response: str = Field(
        ...,
        description="Text reply generated by the agent based on context and store data.",
    )
    session_id: str = Field(
        ...,
        description="Session identifier tied to the active conversation history.",
    )
